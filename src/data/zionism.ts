export function zionismByGroup(): { group: ZionismGroup; label: string; terms: ZionismTerm[] }[] {
  const order: ZionismGroup[] = [
    'ideas',
    'aliya',
    'asentamientos',
    'instituciones',
    'simbolos',
    'lugares',
    'figuras',
  ]
  return order.map((group) => ({
    group,
    label: zionismGroupLabels[group],
    terms: zionismTerms.filter((t) => t.group === group),
  }))
}

export function getZionismTerm(id: string): ZionismTerm | undefined {
  return zionismTerms.find((t) => t.id === id)
}
